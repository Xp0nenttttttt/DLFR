-- DLFR 2.7 : cadres de badges + Level Packs officiels.
-- Requiert les migrations 35 (préférences) et 39 (modération).
-- À tester après sauvegarde de la base. Ne touche pas aux classements.
BEGIN;

ALTER TABLE public.dlfr_profile_preferences
  ADD COLUMN IF NOT EXISTS frame_key text NOT NULL DEFAULT 'none'
  CHECK (length(frame_key) <= 100);

CREATE TABLE IF NOT EXISTS public.dlfr_level_packs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title text NOT NULL CHECK (length(btrim(title)) BETWEEN 3 AND 110),
 description text NOT NULL DEFAULT '' CHECK (length(description) <= 1500),
 banner_url text,
 reward_kind text NOT NULL CHECK (reward_kind IN ('badge','title')),
 reward_label text NOT NULL CHECK (length(btrim(reward_label)) BETWEEN 2 AND 80),
 reward_title_id bigint REFERENCES public.profile_titles(id) ON DELETE SET NULL,
 is_published boolean NOT NULL DEFAULT false,
 created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.dlfr_level_pack_levels (
 pack_id bigint NOT NULL REFERENCES public.dlfr_level_packs(id) ON DELETE CASCADE,
 demon_id bigint NOT NULL REFERENCES public.demons(id) ON DELETE RESTRICT,
 sort_order smallint NOT NULL CHECK (sort_order BETWEEN 1 AND 30),
 PRIMARY KEY(pack_id,demon_id),
 UNIQUE(pack_id,sort_order)
);
CREATE TABLE IF NOT EXISTS public.dlfr_level_pack_claims (
 pack_id bigint NOT NULL REFERENCES public.dlfr_level_packs(id) ON DELETE RESTRICT,
 player_key text NOT NULL REFERENCES public.players(player_key) ON DELETE CASCADE,
 claimed_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(pack_id,player_key)
);
CREATE INDEX IF NOT EXISTS dlfr_level_pack_claims_player_idx ON public.dlfr_level_pack_claims(player_key);
ALTER TABLE public.dlfr_level_packs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dlfr_level_pack_levels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dlfr_level_pack_claims ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.dlfr_level_packs, public.dlfr_level_pack_levels, public.dlfr_level_pack_claims FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.dlfr_level_packs, public.dlfr_level_pack_levels, public.dlfr_level_pack_claims TO anon,authenticated;

DROP POLICY IF EXISTS dlfr_packs_read ON public.dlfr_level_packs;
CREATE POLICY dlfr_packs_read ON public.dlfr_level_packs FOR SELECT TO anon,authenticated
 USING (is_published OR EXISTS (
   SELECT 1 FROM public.staff_roles s WHERE s.auth_user_id=(SELECT auth.uid())
   AND s.role IN ('owner','editor','supermoderator','moderator','nlw')
 ) OR EXISTS (SELECT 1 FROM public.nlw_staff_roles n
             WHERE n.auth_user_id=(SELECT auth.uid())));
DROP POLICY IF EXISTS dlfr_pack_levels_read ON public.dlfr_level_pack_levels;
CREATE POLICY dlfr_pack_levels_read ON public.dlfr_level_pack_levels FOR SELECT TO anon,authenticated
 USING (EXISTS (SELECT 1 FROM public.dlfr_level_packs p WHERE p.id=pack_id));
DROP POLICY IF EXISTS dlfr_pack_claims_read ON public.dlfr_level_pack_claims;
CREATE POLICY dlfr_pack_claims_read ON public.dlfr_level_pack_claims FOR SELECT TO anon,authenticated
 USING (true); -- Récompenses acquises restent visibles après archivage d'un pack.

-- Enregistrement de pack par le personnel. Contrôle d'accès dans Postgres,
-- pas via les boutons JavaScript. Les modos NLW ne publient que des niveaux NLW.
CREATE OR REPLACE FUNCTION public.dlfr_save_level_pack(
 p_pack_id bigint,p_title text,p_description text,p_banner_url text,
 p_reward_kind text,p_reward_label text,p_level_ids bigint[],p_is_published boolean
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE
 v_role text; v_pack bigint; v_count integer; v_order integer; v_demon bigint;
 v_has_claims boolean; v_old public.dlfr_level_packs%ROWTYPE;
 v_title bigint; v_levels bigint[];
BEGIN
 SELECT s.role INTO v_role FROM public.staff_roles s WHERE s.auth_user_id=(SELECT auth.uid());
 IF (v_role IS NULL OR v_role NOT IN ('owner','editor','supermoderator','moderator','nlw')) AND EXISTS(SELECT 1 FROM public.nlw_staff_roles n WHERE n.auth_user_id=(SELECT auth.uid())) THEN v_role:='nlw'; END IF;
 IF v_role IS NULL OR v_role NOT IN ('owner','editor','supermoderator','moderator','nlw')
 THEN RAISE EXCEPTION 'Modération requise'; END IF;
 IF length(btrim(COALESCE(p_title,''))) NOT BETWEEN 3 AND 110
  OR length(COALESCE(p_description,''))>1500
  OR length(btrim(COALESCE(p_reward_label,''))) NOT BETWEEN 2 AND 80
  OR p_reward_kind NOT IN ('badge','title')
 THEN RAISE EXCEPTION 'Informations du pack invalides'; END IF;
 IF NULLIF(btrim(COALESCE(p_banner_url,'')),'') IS NOT NULL AND
    (length(p_banner_url)>500 OR p_banner_url !~* '^https://[^[:space:]]+$')
 THEN RAISE EXCEPTION 'Bannière : URL HTTPS requise'; END IF;
 v_count:=COALESCE(cardinality(p_level_ids),0);
 IF v_count NOT BETWEEN 2 AND 30 OR
    v_count <> (SELECT count(DISTINCT x) FROM unnest(p_level_ids) AS x)
 THEN RAISE EXCEPTION 'Choisis entre 2 et 30 niveaux distincts'; END IF;
 IF EXISTS (
   SELECT 1 FROM unnest(p_level_ids) AS id
   LEFT JOIN public.demons d ON d.id=id
   WHERE d.id IS NULL OR d.is_public IS DISTINCT FROM true OR d.legacy IS TRUE OR d.unrated IS TRUE
     OR (v_role='nlw' AND (d.position<=150 OR d.position>=100000000))
 ) THEN RAISE EXCEPTION 'Niveau inaccessible ou non autorisé pour ce rôle'; END IF;
 IF p_pack_id IS NOT NULL THEN
  SELECT * INTO v_old FROM public.dlfr_level_packs WHERE id=p_pack_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pack introuvable'; END IF;
  SELECT EXISTS(SELECT 1 FROM public.dlfr_level_pack_claims WHERE pack_id=p_pack_id) INTO v_has_claims;
  IF v_has_claims THEN
    SELECT array_agg(demon_id ORDER BY sort_order) INTO v_levels
      FROM public.dlfr_level_pack_levels WHERE pack_id=p_pack_id;
    IF v_old.reward_kind<>p_reward_kind OR v_old.reward_label<>btrim(p_reward_label)
       OR v_levels IS DISTINCT FROM p_level_ids THEN
       RAISE EXCEPTION 'Pack déjà récompensé : niveaux et récompense verrouillés';
    END IF;
  END IF;
  -- NLW doit rester limité à son périmètre même si un pack a été créé par un supermodo.
  IF v_role='nlw' AND EXISTS (
    SELECT 1 FROM public.dlfr_level_pack_levels l JOIN public.demons d ON d.id=l.demon_id
    WHERE l.pack_id=p_pack_id AND (d.position<=150 OR d.position>=100000000)
  ) THEN RAISE EXCEPTION 'Ce pack contient des niveaux hors NLW'; END IF;
  v_pack:=p_pack_id;
  v_title:=v_old.reward_title_id;
 ELSE
  v_title:=NULL;
  INSERT INTO public.dlfr_level_packs(title,description,reward_kind,reward_label,is_published,created_by)
  VALUES(btrim(p_title),COALESCE(p_description,''),p_reward_kind,btrim(p_reward_label),false,(SELECT auth.uid()))
  RETURNING id INTO v_pack;
 END IF;
 -- Le titre officiel ne peut pas être choisi/arbitrairement accordé par le joueur.
 IF p_reward_kind='title' THEN
   IF v_title IS NULL THEN
     INSERT INTO public.profile_titles(label,description,color,is_active)
     VALUES(btrim(p_reward_label),'Récompense Level Pack', '#6c62c6',true)
     RETURNING id INTO v_title;
   ELSE
     UPDATE public.profile_titles SET label=btrim(p_reward_label) WHERE id=v_title;
   END IF;
 END IF;
 UPDATE public.dlfr_level_packs SET
   title=btrim(p_title),description=COALESCE(p_description,''),
   banner_url=NULLIF(btrim(COALESCE(p_banner_url,'')),''),
   reward_kind=p_reward_kind,reward_label=btrim(p_reward_label),
   reward_title_id=CASE WHEN p_reward_kind='title' THEN v_title ELSE NULL END,
   is_published=COALESCE(p_is_published,false),updated_at=now()
 WHERE id=v_pack;
 DELETE FROM public.dlfr_level_pack_levels WHERE pack_id=v_pack;
 FOR v_order IN 1..v_count LOOP
  v_demon:=p_level_ids[v_order];
  INSERT INTO public.dlfr_level_pack_levels(pack_id,demon_id,sort_order)
  VALUES(v_pack,v_demon,v_order);
 END LOOP;
 RETURN v_pack;
END $$;
REVOKE ALL ON FUNCTION public.dlfr_save_level_pack(bigint,text,text,text,text,text,bigint[],boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.dlfr_save_level_pack(bigint,text,text,text,text,text,bigint[],boolean) TO authenticated;

-- La récompense est obtenue sur demande, et contrôlée sur les complétions
-- approuvées (table publique completions, progression 100 %). Aucun client ne
-- peut attribuer directement un titre ou un badge.
CREATE OR REPLACE FUNCTION public.dlfr_claim_level_pack(p_pack_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_player text; v_pack public.dlfr_level_packs%ROWTYPE; v_missing bigint; v_already boolean;
BEGIN
 IF (SELECT auth.uid()) IS NULL THEN RAISE EXCEPTION 'Connexion requise'; END IF;
 SELECT o.player_key INTO v_player FROM public.player_profile_owners o
 WHERE o.auth_user_id=(SELECT auth.uid()) LIMIT 1;
 IF v_player IS NULL THEN RAISE EXCEPTION 'Profil joueur non lié'; END IF;
 SELECT * INTO v_pack FROM public.dlfr_level_packs WHERE id=p_pack_id AND is_published=true FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Pack non publié'; END IF;
 SELECT EXISTS(SELECT 1 FROM public.dlfr_level_pack_claims WHERE pack_id=p_pack_id AND player_key=v_player) INTO v_already;
 IF v_already THEN RETURN 'already_claimed'; END IF;
 SELECT count(*) INTO v_missing FROM public.dlfr_level_pack_levels l
 JOIN public.demons d ON d.id=l.demon_id
 WHERE l.pack_id=p_pack_id AND (
   d.is_public IS DISTINCT FROM true OR d.legacy IS TRUE OR d.unrated IS TRUE OR
   NOT EXISTS(SELECT 1 FROM public.completions c
      WHERE c.demon_id=l.demon_id AND c.progress=100
       AND lower(btrim(c.player))=lower(btrim(v_player)))
 );
 IF v_missing>0 OR NOT EXISTS(SELECT 1 FROM public.dlfr_level_pack_levels WHERE pack_id=p_pack_id)
 THEN RAISE EXCEPTION 'Tous les niveaux du pack doivent avoir une complétion validée à 100 %%'; END IF;
 INSERT INTO public.dlfr_level_pack_claims(pack_id,player_key) VALUES(p_pack_id,v_player);
 IF v_pack.reward_kind='title' AND v_pack.reward_title_id IS NOT NULL THEN
  INSERT INTO public.player_profile_titles(player_key,title_id)
  VALUES(v_player,v_pack.reward_title_id) ON CONFLICT DO NOTHING;
 END IF;
 RETURN 'claimed';
END $$;
REVOKE ALL ON FUNCTION public.dlfr_claim_level_pack(bigint) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.dlfr_claim_level_pack(bigint) TO authenticated;

CREATE OR REPLACE FUNCTION public.dlfr_choose_profile_frame(p_frame_key text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE v_player text; v_badge text; v_pack bigint;
BEGIN
 SELECT o.player_key INTO v_player FROM public.player_profile_owners o
 WHERE o.auth_user_id=(SELECT auth.uid()) LIMIT 1;
 IF v_player IS NULL THEN RAISE EXCEPTION 'Profil joueur non lié'; END IF;
 IF p_frame_key IS NULL OR p_frame_key='none' THEN p_frame_key:='none';
 ELSIF p_frame_key LIKE 'badge:%' THEN
  v_badge:=substring(p_frame_key from 7);
  IF v_badge='' OR NOT EXISTS(SELECT 1 FROM public.badge_awards a
     WHERE a.player_key=v_player AND a.badge_id::text=v_badge) THEN
    RAISE EXCEPTION 'Badge requis pour ce cadre'; END IF;
 ELSIF p_frame_key='achievement:fr' THEN
  IF NOT EXISTS(SELECT 1 FROM public.fr_achievements a WHERE a.player_key=v_player) THEN
    RAISE EXCEPTION 'Un achievement FR est requis'; END IF;
 ELSIF p_frame_key='achievement:hall' THEN
  IF NOT EXISTS(SELECT 1 FROM public.hall_of_fame h WHERE h.player_key=v_player AND h.is_published=true) THEN
    RAISE EXCEPTION 'Une distinction Hall of Fame est requise'; END IF;
 ELSIF p_frame_key ~ '^pack:[0-9]{1,18}$' THEN
  v_pack:=substring(p_frame_key from 6)::bigint;
  IF NOT EXISTS(SELECT 1 FROM public.dlfr_level_pack_claims c
    JOIN public.dlfr_level_packs p ON p.id=c.pack_id
    WHERE c.player_key=v_player AND c.pack_id=v_pack AND p.reward_kind='badge') THEN
    RAISE EXCEPTION 'Récompense Level Pack requise pour ce cadre'; END IF;
 ELSE RAISE EXCEPTION 'Cadre inconnu'; END IF;
 INSERT INTO public.dlfr_profile_preferences(player_key,frame_key)
 VALUES(v_player,p_frame_key)
 ON CONFLICT(player_key) DO UPDATE SET frame_key=EXCLUDED.frame_key,updated_at=now();
END $$;
REVOKE ALL ON FUNCTION public.dlfr_choose_profile_frame(text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.dlfr_choose_profile_frame(text) TO authenticated;
COMMIT;
