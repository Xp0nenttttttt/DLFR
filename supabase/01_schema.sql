create table if not exists public.players (
  player_key text primary key,
  legacy_id bigint unique,
  username text not null,
  display_name text,
  country_code text,
  has_account boolean not null default false,
  legacy_role text not null default 'player',
  points numeric(12,2) not null default 0,
  bonus_points numeric(12,2) not null default 0,
  hidden_from_stats boolean not null default false,
  created_at timestamptz default now()
);
create table if not exists public.demons (
  id bigint generated by default as identity primary key,
  position integer not null unique check (position > 0),
  name text not null unique,
  difficulty text not null default 'Extreme Demon',
  requirement integer not null default 100 check (requirement between 1 and 100),
  creator text, creator_more text,
  publisher text not null default '', verifier text,
  publisher_user_id bigint, verifier_user_id bigint,
  video_url text, thumbnail_url text, description text,
  level_id text, level_length text, song text, object_count integer,
  legacy boolean not null default false,
  created_at timestamptz default now()
);
create table if not exists public.completions (
  id bigint generated by default as identity primary key,
  demon_id bigint not null references public.demons(id) on delete cascade,
  player text not null,
  video_url text, progress integer not null default 100 check (progress between 1 and 100),
  placement integer, created_at timestamptz default now(),
  unique(demon_id, player)
);
create index if not exists idx_completions_player on public.completions (lower(player));
create index if not exists idx_completions_created on public.completions(created_at);

create table if not exists public.news_items (
 id bigint generated by default as identity primary key,
 headline text not null, body text not null, player_name text,
 image_url text, video_url text,
 is_published boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.profile_titles (
 id bigint generated by default as identity primary key,
 label text not null, description text, color text not null default '#287bba',
 is_active boolean not null default true
);
create table if not exists public.player_profile_titles (
 player_key text not null references public.players(player_key) on delete cascade,
 title_id bigint not null references public.profile_titles(id) on delete cascade,
 primary key(player_key,title_id)
);
create table if not exists public.player_profiles (
 player_key text primary key references public.players(player_key) on delete cascade,
 bio text, banner_url text, social_url text,
 avatar_url text, join_year integer, favorite_level text, current_goal text, youtube_url text, twitch_url text,
 highlight_1 text, highlight_2 text, highlight_3 text,
 updated_at timestamptz not null default now()
);
create table if not exists public.hall_of_fame (
 id bigint generated by default as identity primary key,
 player_key text not null,
 headline text not null, description text, award_year integer,
 category text not null default 'Accomplissement', source_url text,
 is_published boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.player_stat_snapshots (
 snapshot_day date not null, player_key text not null,
 points numeric(12,2) not null default 0, rank_position integer,
 completions integer not null default 0, hardest_demon text,
 primary key(snapshot_day,player_key)
);
create table if not exists public.demon_position_history (
 id bigint generated by default as identity primary key,
 demon_id bigint not null references public.demons(id) on delete cascade,
 old_position integer, new_position integer not null,
 note text, created_at timestamptz default now()
);
create table if not exists public.site_settings (
 id integer primary key check(id=1),
 main_limit integer not null default 75,
 extended_limit integer not null default 150,
 top1_points numeric(10,2) not null default 350.00,
 legacy_scores boolean not null default false
);
insert into public.site_settings(id) values (1) on conflict(id) do nothing;

-- Les rôles des modérateurs sont gérés UNIQUEMENT depuis l'éditeur SQL Supabase.
-- Ne jamais reprendre automatiquement le rôle 'owner' d'une exportation MySQL.
create table if not exists public.staff_roles (
 auth_user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null check(role in ('helper','editor','owner'))
);
create table if not exists public.community_audit_log (
 id bigint generated always as identity primary key,
 actor_user_id uuid,
 action_key text not null,
 target text not null,
 details text,
 created_at timestamptz not null default now()
);

-- Sur GitHub Pages, la clé publique est exposée : toutes les écritures sont donc
-- sécurisées CÔTÉ POSTGRES par RLS, jamais uniquement par un bouton JS.
create or replace function public.is_demonlist_staff()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (
 select 1 from public.staff_roles s
 where s.auth_user_id = (select auth.uid()) and s.role in ('helper','editor','owner')
); $$;
revoke all on function public.is_demonlist_staff() from public;
grant execute on function public.is_demonlist_staff() to anon, authenticated;

