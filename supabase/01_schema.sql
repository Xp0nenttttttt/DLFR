-- Audit automatique. Pas d'écriture du journal possible depuis le navigateur.
create or replace function public.log_staff_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.community_audit_log(actor_user_id,action_key,target,details)
  values (auth.uid(),TG_OP, TG_TABLE_NAME,
    case when TG_OP = 'DELETE' then left(old::text,300) else left(new::text,300) end);
  return case when TG_OP = 'DELETE' then old else new end;
end; $$;
revoke all on function public.log_staff_change() from public;
do $$ declare t text; begin
  foreach t in array array['players','demons','completions','news_items','profile_titles',
    'player_profile_titles','player_profiles','hall_of_fame','site_settings'] loop
    execute format('create trigger log_%s_change after insert or update or delete on public.%I for each row execute function public.log_staff_change()',t,t);
  end loop;
end $$;

