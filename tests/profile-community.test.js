const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/profile-community.js'),'utf8'),ctx);
const m=ctx.window.DLFR_COMMUNITY;
assert.equal(m.hex('#FA23ac'),'#fa23ac');
assert.equal(m.hex('url(javascript:evil)'),'#287bba');
const badges={definitions:[{id:'b1',label:'Badge 1'}],visibleAwards:()=>[{badge_id:'b1'},{badge_id:'not-a-badge'}]};
const data={player_profile_titles:[{player_key:'me',title_id:2}],profile_titles:[{id:2,label:'Top 1',is_active:true}],dlfr_profile_showcase:[{player_key:'me',slot:3},{player_key:'me',slot:1},{player_key:'other',slot:2}],dlfr_profile_follows:[{follower_key:'me',followed_key:'you'},{follower_key:'other',followed_key:'me'}]};
assert.equal(m.ownedBadges(data,'me',badges).length,1);
assert.equal(m.ownedTitles(data,'me').length,1);
assert.deepEqual(Array.from(m.showcase(data,'me'),x=>x.slot),[1,3]);
assert.equal(m.followers(data,'me').length,1);
assert.equal(m.following(data,'me').length,1);
console.log('DLFR 2.0 profils communautaires : OK');
