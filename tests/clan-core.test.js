const assert=require('node:assert/strict');
const Clan=require('../js/clan-core.js');
let d={players:['alice','bob','charlie','dave'].map(p=>({player_key:p,has_account:true,hidden_from_stats:false})),clans:[],clan_members:[],clan_invites:[]};
const doAction=(type,actor,extra={})=>d=Clan.apply(d,{type,actor,...extra});
const fails=(fn,msg)=>assert.throws(fn, msg ? new RegExp(msg,'i'):undefined);
doAction('create','alice',{name:'La Constellation',tag:'CST',description:'Test',color:'#123456'});
assert.equal(d.clans.length,1);assert.equal(Clan.member(d,'alice').role,'leader');
fails(()=>doAction('create','alice',{name:'Second Clan',tag:'SEC'}),'clan');
doAction('invite','alice',{clan_id:1,target:'bob'});
fails(()=>doAction('invite','alice',{clan_id:1,target:'bob'}),'attente');
fails(()=>doAction('accept','charlie',{invite_id:1}),'indisponible');
doAction('accept','bob',{invite_id:1});
assert.equal(Clan.member(d,'bob').role,'member');
fails(()=>doAction('invite','alice',{clan_id:1,target:'bob'}),'déjà');
fails(()=>doAction('remove','bob',{clan_id:1,target:'alice'}),'chef');
fails(()=>doAction('leave','alice'),'direction');
doAction('transfer','alice',{clan_id:1,target:'bob'});
assert.equal(Clan.member(d,'bob').role,'leader');
assert.equal(Clan.member(d,'alice').role,'member');
doAction('leave','alice');assert.equal(Clan.member(d,'alice'),null);
doAction('invite','bob',{clan_id:1,target:'charlie'});doAction('decline','charlie',{invite_id:2});assert.equal(Clan.member(d,'charlie'),null);
doAction('invite','bob',{clan_id:1,target:'charlie'});doAction('cancel','bob',{invite_id:3});assert.equal(d.clan_invites.find(i=>i.id===3).status,'cancelled');
doAction('disband','bob',{clan_id:1});assert.equal(d.clans.length,0);assert.equal(d.clan_members.length,0);
console.log('Clan engine: all lifecycle and authorization-simulation tests passed');
