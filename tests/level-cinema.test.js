const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const cinema=require('../js/level-cinema.js');
const esc=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const url=(page,p={})=>'?' + new URLSearchParams({page,...p});
const demon={id:260,name:'Shardscapes',position:155,level_id:'79997992',difficulty:'Extreme Demon',requirement:100,creator:'<img>',publisher:'À renseigner',verifier:'[GUI] Boodbdog',video_url:'https://youtu.be/1nH-LccRhug?t=5',thumbnail_url:'https://i.ytimg.com/vi/1nH-LccRhug/maxresdefault.jpg',created_at:'2026-10-14T10:00:00Z',first_fr_player:'Alice',first_fr_achieved_at:'2026-09-30T12:00:00Z'};
const records=[{player:'Alice',progress:100,created_at:'2026-10-15T12:00:00Z',video_url:'https://youtu.be/1nH-LccRhug'},{player:'Bob',progress:72,created_at:'2026-10-15T12:00:00Z'},{player:'Alice',progress:94,created_at:'2026-10-14T12:00:00Z'},{player:'NoName',progress:100,created_at:'2026-10-10T12:00:00Z'}];
const players=[{player_key:'alice',username:'Alice',display_name:'Alice',country_code:'FR',score:500},{player_key:'bob',username:'Bob',country_code:'FR',score:900},{player_key:'nom',username:'NoName',country_code:'BE',score:999}];
assert.equal(cinema.youtubeId('https://youtu.be/1nH-LccRhug?t=1'),'1nH-LccRhug');
assert.equal(cinema.youtubeId('https://www.youtube.com/watch?v=1nH-LccRhug'),'1nH-LccRhug');
assert.equal(cinema.youtubeId('https://youtube.com/shorts/1nH-LccRhug'),'1nH-LccRhug');
assert.equal(cinema.youtubeId('https://evil.youtube.com/watch?v=1nH-LccRhug'),'');
assert.equal(cinema.youtubeId('javascript:alert(1)'),'');
assert.equal(cinema.safeUrl('javascript:alert(1)'),'');
assert.equal(cinema.embedHtml('https://example.com/test',esc),'');
assert.match(cinema.embedHtml(demon.video_url,esc),/youtube-nocookie.com\/embed\/1nH-LccRhug/);
assert.equal(cinema.bestFrench(records,players).length,1);
assert.equal(cinema.bestFrench(records,players)[0].player_key,'alice');
assert.equal(cinema.timeline(demon,[]).length,2);
assert.equal(cinema.timeline({...demon,first_fr_achieved_at:null},[]).some(e=>e.label.includes('Premier record')),false);
const html=cinema.render(demon,{escape:esc,link:url,records,players,status:'NLW #5',points:'95,56 points NLW',format:n=>Number(n).toFixed(2),formatDate:()=> '15/10/2026'});
assert.match(html,/DLFR|DEMONLIST FRANCOPHONE/);
assert.match(html,/NLW #5/);
assert.match(html,/95,56 points NLW/);
assert.match(html,/Lancer la vidéo/);
assert.match(html,/Premier record français daté retrouvé/);
assert.match(html,/Enregistré le/);
assert.match(html,/Joueurs français/);
assert.match(html,/alice/);
assert.ok(!html.includes('<img>')); // HTML utilisateur échappé
assert.ok(!html.includes('class="dlfr23-player-name">Bob')); // Pas de faux podium pour un 72 %
const noVideo=cinema.render({...demon,video_url:null,verifier_video_url:null,thumbnail_url:null,first_fr_video_url:null,first_fr_achieved_at:null},{escape:esc,link:url,records:[],players:[]});
assert.ok(noVideo.includes('Aucune vidéo du niveau'));
assert.ok(noVideo.includes('Aucun record enregistré'));
const app=fs.readFileSync(path.resolve(__dirname,'../js/app.js'),'utf8');
const index=fs.readFileSync(path.resolve(__dirname,'../index.html'),'utf8');
assert.match(index,/js\/level-cinema\.js\?v=dlfr23-1/);
assert.match(app,/window\.DLFR_LEVEL_CINEMA\.render/);
assert.match(app,/data-dlfr23-play/);
console.log('DLFR 2.3 cinéma : tests OK');
