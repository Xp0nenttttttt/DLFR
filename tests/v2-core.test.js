const assert=require('node:assert/strict');
const v=require('../js/v2-core.js');
const base=[{id:1,name:'First',position:1,verifier:'Alpha'},{id:2,name:'Rank 150',position:150,verifier:'Alpha'},{id:3,name:'Rank 151',position:151,legacy:true,legacy_since:'2026-06-01',verifier:'Alpha'}];
const player={player_key:'alpha',username:'Alpha'};
const records=[{demon_id:1,player:'Alpha',progress:100},{demon_id:2,player:'Alpha',progress:100},{demon_id:3,player:'Alpha',progress:100,created_at:'2026-07-01'}];
assert.equal(v.nlwRank(base[2]),1);
assert.equal(v.nlwPoints(base[2]),100);
assert.ok(v.actualPoints(base[1])>0);
assert.equal(v.actualPoints(base[2]),0);
assert.equal(v.historicalLegacy(records[2],base[2]),false,'no legacy if beat after exit');
assert.equal(v.historicalLegacy({...records[2],created_at:'2026-04-01'},base[2]),true);
assert.equal(v.historicalLegacy({...records[2],created_at:''},{...base[2],legacy_since:null}),false);
const badges=v.badges(player,base,records);
assert.equal(badges.find(b=>b.id==='Faucheur de liste').goal,1);
assert.equal(badges.find(b=>b.id==='Vérificateur').goal,1);
assert.equal(badges.find(b=>b.id==='Amateur de difficulté').goal,1);
const promoted=[{...base[0],position:160},base[1],base[2]];
const after=v.badges(player,promoted,records);
assert.equal(after.find(b=>b.id==='Faucheur de liste').goal,1,'reaper shrinks to one active level');
assert.equal(after.find(b=>b.id==='Vérificateur').goal,1,'verifier persists');
const alt=v.decorate([...base,{id:4,name:'Unrated',unrated:true,unrated_position:1}],true);
assert.equal(alt.find(d=>d.id===4).position,1);
assert.equal(alt.find(d=>d.id===1).position,2);
assert.equal(base[0].position,1,'input unchanged');
const proj=v.project([player],base,records);
assert.equal(proj[0].main_count,2);
assert.equal(proj[0].nlw_count,1);
assert.ok(proj[0].main_score>0&&proj[0].nlw_score===100);
assert.deepEqual(v.parseAredl('name,rank\nCognition,92\n"My, Level",4'),[{name:'Cognition',aredl_rank:'92'},{name:'My, Level',aredl_rank:'4'}]);
console.log('V2 core rules PASS');
